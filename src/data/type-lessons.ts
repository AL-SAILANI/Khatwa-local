import type { Lesson } from "@/types/course";

/**
 * Lessons organised by question type or rule routine. Notes use the same
 * marked template as the older lessons (central rule, quick form, STEP trap,
 * spaced review, optional technique) so the lesson viewer renders them as cards.
 * Written from the project's own curriculum notes (docs/), not copied.
 */
interface NoteParts {
  rule: string;
  quick: string[];
  trap: string;
  review: [string, string, string, string];
  technique?: string;
}

function notes({ rule, quick, trap, review, technique }: NoteParts): string {
  const days = [1, 3, 7, 14];
  return [
    `📌 القاعدة المركزية:\n${rule}`,
    `⚡ الصيغة السريعة:\n${quick.map((line) => `• ${line}`).join("\n")}`,
    `⚠️ فخ STEP:\n${trap}`,
    `🔄 مراجعة متباعدة:\n${review.map((line, i) => `• اليوم ${days[i]} — ${line}`).join("\n")}`,
    ...(technique ? [`🧭 ${technique}`] : []),
  ].join("\n\n");
}

const lesson = (
  id: string,
  courseId: string,
  order: number,
  title: string,
  noteParts: NoteParts,
  questionIds: string[],
): Lesson => ({
  id,
  courseId,
  title,
  order,
  resources: [],
  notes: notes(noteParts),
  questionIds,
});

