const STEP_MOCK_2_QUESTIONS: Question[] = [
  ...STEP_MOCK_2_READING_QUESTIONS,
  ...STEP_MOCK_2_GRAMMAR_QUESTIONS,
  ...STEP_MOCK_2_LISTENING_QUESTIONS,
  ...STEP_MOCK_2_WRITING_QUESTIONS,
];

const str = (v: unknown) => (v == null ? "null" : `'${String(v).replace(/'/g, "''")}'`);
const num = (v: unknown) => (v == null ? "null" : String(Number(v)));
const arr = (v: string[] | undefined) =>
  `array[${(v ?? []).map(str).join(",")}]::text[]`;
const json = (v: unknown) => `${str(JSON.stringify(v ?? null))}::jsonb`;

function upsert(table: string, cols: Record<string, string>) {
  const names = Object.keys(cols);
  const updates = names.filter((n) => n !== "id").map((n) => `${n} = excluded.${n}`);
  return (
    `insert into public.${table} (${names.map((n) => (n === "order" ? '"order"' : n)).join(", ")}) ` +
    `values (${names.map((n) => cols[n]).join(", ")}) ` +
    `on conflict (id) do update set ${updates.map((u) => u.replace(/^order =/, '"order" =')).join(", ")};`
  );
}

const out: string[] = ["-- Generated by scripts/export-seed-sql.ts. Do not edit by hand.", "begin;"];

for (const c of SAMPLE_COURSES) {
  out.push(upsert("courses", {
    id: str(c.id), track: str(c.track), title: str(c.title), description: str(c.description),
    order: num(c.order), lesson_count: num(c.lessonCount),
    estimated_minutes: num(c.estimatedMinutes), cover_image: str(c.coverImage),
  }));
}
for (const l of SAMPLE_LESSONS) {
  out.push(upsert("lessons", {
    id: str(l.id), course_id: str(l.courseId), title: str(l.title), order: num(l.order),
    resources: json(l.resources), notes: str(l.notes), question_ids: arr(l.questionIds),
  }));
}
for (const p of [...SAMPLE_READING_PASSAGES, ...STEP_MOCK_READING_PASSAGES, ...STEP_MOCK_2_READING_PASSAGES, ...STEP_MOCK_3_READING_PASSAGES, ...STEP_MOCK_4_READING_PASSAGES, ...STEP_MOCK_5_READING_PASSAGES, ...LESSON_PRACTICE_READING_PASSAGES]) {
  out.push(upsert("reading_passages", {
    id: str(p.id), title: str(p.title), body: str(p.body), question_ids: arr(p.questionIds),
  }));
}
for (const q of [...SAMPLE_QUESTIONS, ...GRAMMAR_EXTRA_QUESTIONS, ...LESSON_PRACTICE_GRAMMAR_QUESTIONS, ...LESSON_PRACTICE_WRITING_QUESTIONS, ...LESSON_PRACTICE_READING_QUESTIONS, ...LESSON_PRACTICE_LISTENING_QUESTIONS, ...STEP_MOCK_QUESTIONS, ...STEP_MOCK_2_QUESTIONS, ...STEP_MOCK_3_QUESTIONS, ...STEP_MOCK_4_QUESTIONS, ...STEP_MOCK_5_QUESTIONS]) {
  out.push(upsert("questions", {
    id: str(q.id), section: str(q.section), course_id: str(q.courseId),
    passage_id: str(q.passageId), audio_url: str(q.audioUrl), transcript: str(q.transcript),
    prompt: str(q.prompt), options: json(q.options), correct_option_id: str(q.correctOptionId),
    explanation: str(q.explanation), difficulty: str(q.difficulty), tags: arr(q.tags),
  }));
}
for (const w of SAMPLE_VOCAB_WORDS) {
  out.push(upsert("vocab_words", {
    id: str(w.id), word: str(w.word), meaning_ar: str(w.meaningAr), meaning_en: str(w.meaningEn),
    example: str(w.example), audio_url: str(w.audioUrl), level: str(w.level), tags: arr(w.tags),
  }));
}
for (const a of ACHIEVEMENTS) {
  out.push(upsert("achievements", {
    id: str(a.id), title: str(a.title), description: str(a.description), icon: str(a.icon),
    xp_reward: num(a.xpReward), category: str(a.category),
  }));
}
out.push("commit;");

writeFileSync("supabase/seed.sql", out.join("\n") + "\n");
console.log(`Wrote supabase/seed.sql (${out.length - 3} rows)`);
